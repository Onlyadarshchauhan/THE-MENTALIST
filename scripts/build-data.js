#!/usr/bin/env node
// Builds data/generated/data.js from the source CSVs so index.html can open
// straight from disk (browsers block fetch() of local files).
// The source CSVs are read, never modified. Any unexpected value stops the build.
'use strict';
const fs = require('fs');
const path = require('path');
const R = require('../assets/rules.js');

const ROOT = path.join(__dirname, '..');

function loadDataset() {
  const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
  const rows = R.parseCsv(read('data/source/bhopal_ghats_2023_2025.csv'));
  const criteria = R.parseCsv(read('data/source/cpcb_water_quality_criteria.csv'));
  const ds = R.buildDataset(rows, criteria);
  const config = JSON.parse(read('data/ghats_2026.json'));
  ds.ghats.forEach((g) => {
    if (!config.ghats[g.id]) throw new Error('data/ghats_2026.json has no entry for ghat id "' + g.id + '"');
  });
  return { ds, config, criteria };
}

if (require.main === module) {
  const { ds, config, criteria } = loadDataset();
  for (const y of ds.years) {
    const f = path.join(ROOT, 'reports', R.REPORTS[y].file);
    if (!fs.existsSync(f)) throw new Error('Missing source report: ' + f);
  }
  const out = {
    builtFrom: 'data/source/bhopal_ghats_2023_2025.csv + data/source/cpcb_water_quality_criteria.csv',
    readings: ds.readings,
    thresholds: ds.thresholds,
    years: ds.years,
    ghats: ds.ghats,
    criteria,
    config
  };
  const dest = path.join(ROOT, 'data/generated/data.js');
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, '// Generated by scripts/build-data.js. Do not edit by hand.\nwindow.VGW_DATA = ' + JSON.stringify(out) + ';\n');
  const missing = R.missingEvents(ds);
  console.log('Wrote ' + path.relative(ROOT, dest) + ': ' + ds.readings.length + ' readings, ' + ds.ghats.length + ' ghats, ' + missing.length + ' missing events');
}

module.exports = { loadDataset };
